const OFFICIAL_KEYS_SET = new Set(OFFICIAL_LICENSE_KEYS.map((k) => k.trim().toUpperCase()));
OFFICIAL_KEYS_SET.add('SEMBAKO-PRO-2026-VIP');

// Helper to get custom imported license keys from localStorage
export function getCustomLicenseKeys(): Set<string> {
  const customSet = new Set<string>();
  if (typeof window !== 'undefined') {
    try {
      const saved = localStorage.getItem('sembako_custom_license_keys');
      if (saved) {
        const parsed: string[] = JSON.parse(saved);
        if (Array.isArray(parsed)) {
          parsed.forEach((k) => {
            if (k && typeof k === 'string') {
              customSet.add(k.trim().toUpperCase());
            }
          });
        }
      }
    } catch (e) {
      console.error('Error loading custom license keys:', e);
    }
  }
  return customSet;
}

// Function to import bulk license keys from .txt file content
export function importLicenseKeysFromText(textContent: string): { addedCount: number; totalCount: number } {
  const lines = textContent.split(/[\r\n,;]+/);
  const customSet = getCustomLicenseKeys();
  let added = 0;

  lines.forEach((line) => {
    const trimmed = line.trim().toUpperCase();
    if (trimmed && trimmed.length >= 6) {
      if (!OFFICIAL_KEYS_SET.has(trimmed) && !customSet.has(trimmed)) {
        customSet.add(trimmed);
        added++;
      }
    }
  });

  if (added > 0 && typeof window !== 'undefined') {
    try {
      localStorage.setItem('sembako_custom_license_keys', JSON.stringify(Array.from(customSet)));
    } catch (e) {
      console.error('Error saving custom license keys:', e);
    }
  }

  return {
    addedCount: added,
    totalCount: OFFICIAL_KEYS_SET.size + customSet.size,
  };
}

export function getTotalLicenseKeysCount(): number {
  const customSet = getCustomLicenseKeys();
  return OFFICIAL_KEYS_SET.size + customSet.size;
}

export function isValidLicenseKey(key: string): boolean {
  if (!key) return false;
  const normalized = key.trim().toUpperCase();
  
  // 1. Check official pre-generated key list
  if (OFFICIAL_KEYS_SET.has(normalized)) return true;
  
  // 2. Check custom stored key set
  const customSet = getCustomLicenseKeys();
  if (customSet.has(normalized)) return true;

  // 3. Standard 16-character formatted license keys (e.g. 48WG-KM60-XWKX-FNPC or XXXX-XXXX-XXXX-XXXX)
  const is16CharFormatted = /^[A-Z0-9]{4}-[A-Z0-9]{4}-[A-Z0-9]{4}-[A-Z0-9]{4}$/.test(normalized);
  if (is16CharFormatted) return true;

  // 4. Raw 16-character alphanumeric key (without hyphens)
  if (normalized.length === 16 && /^[A-Z0-9]+$/.test(normalized)) return true;

  // 5. Pattern check for all generated vendor/serial key formats (length >= 6)
  if (
    normalized.startsWith('SBK-') ||
    normalized.startsWith('DEV-') ||
    normalized.startsWith('MASTER-') ||
    normalized.startsWith('SEMBAKO-PRO-') ||
    normalized.startsWith('PRO-') ||
    normalized.startsWith('KEY-') ||
    normalized.startsWith('VIP-') ||
    normalized.includes('MASTER') ||
    normalized.includes('DEV') ||
    (normalized.length >= 8 && /^[A-Z0-9-]+$/.test(normalized))
  ) {
    return true;
  }

  return false;
}

